// 发布的编号：名字去掉空白和标点后小写。括号里的内容保留（“Gemini 2.5 Pro（正式版）”和“Gemini 2.5 Pro”是两款，编号不能撞）。
export const relId = name => String(name).normalize('NFKC').toLowerCase().replace(/[\s\-_·.()]/g, '');

// 只知道月份时落在当月哪一天：按 id 散列，避开月初扎堆。和 sim/clock.js 的 dayInMonth 是同一个算法，
// 这里留一份是因为 data/ 不能依赖 sim/（界面直接导入 data/）；tests/career/rivals_data.test.mjs 保证两边一致。
function hashDay(ym, id, from = 2, to = 26) {
  let h = 2166136261;
  for (const ch of `${id}|day`) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  const [y, m] = ym.split('-').map(Number);
  const last = Math.min(to, new Date(Date.UTC(y, m, 0)).getUTCDate());
  return `${ym}-${String(from + Math.floor((((h >>> 0) % 100000) / 100000) * (last - from + 1))).padStart(2, '0')}`;
}

// 发布日：手写的覆盖生成的；日期必须落在 RAW 行的月份里，对不上或没有就用 hashDay 哈希兜底（dayExact 为 false）。
// approx 条目有出处但具体日待核实，也不算 dayExact。
function dayOf(name, date, id) {
  const ov = RELEASE_DAYS_OVERRIDES[name];
  const day = ov?.day ?? RELEASE_DAYS_GEN[name];
  if (day && day.slice(0, 7) === date) return { day, dayExact: !ov?.approx };
  return { day: hashDay(date, id), dayExact: false };
}

export let RELEASES = [];
// 全部发布按月份排好（同月保持 RAW 行序），换表时整个重建。每条另带 id、day（'YYYY-MM-DD'）、dayExact、tags，
// 以及 ord（RAW 里的行号：同一天同分时取行序靠后的，规格 D1）。
// “谁最强”“截至哪天能看到”一律按 day 算，在 sim/sota.js（familyBest、orgBest、benchBest）；这里不再有“最新一款”的口径。
export function setReleases(rows) {
  RELEASES = rows.map(([family, date, name, cls, open, vals, price, tags], ord) => {
    const f = FAMILIES[family];
    const keys = dimKeys(f.mod);
    const id = relId(name);
    return { family, date, name, id, ...dayOf(name, date, id), ord, cls, open: !!open, price, mod: f.mod, tags: tags ? tags.split(',') : [], dims: Object.fromEntries(keys.map((k, i) => [k, vals[i] ?? 0])) };
  }).sort((a, b) => a.date.localeCompare(b.date));
}
