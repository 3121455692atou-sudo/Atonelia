import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import {readLog} from '../../server/store.mjs';
import {validateAutomationSetup} from '../../server/automation_setup.mjs';
import {defaultAutomationModes} from '../../src/career/data/automation_controls.js';
import {tmpDir,startServer,stopServer,api,Client,waitFor,replayHash} from '../helpers/mp_server.mjs';
const ok=r=>{assert.equal(r.status,200,r.text);assert.equal(r.json.ok,true,r.text);return r.json;};
test('real lobby per-seat presets, validation/ready cancellation, batch ACK and WAL/snapshot recovery',async t=>{
 const data=tmpDir();let srv=await startServer({data,args:['--tick-ms','10000']}),clients=[];
 t.after(async()=>{clients.forEach(c=>c.close());await stopServer(srv);});
 const made=await api(srv.base,'/api/rooms',{method:'POST',body:{lobby:true,settings:{humans:2,bots:1,years:1,seed:72}}});const room=ok(made).room;
 const joined=await api(srv.base,`/api/r/${room}/join`,{method:'POST',body:{seat:1}});const peerId=ok(joined).member;
 let host=new Client(srv.base,room,made.cookie),peer=new Client(srv.base,room,joined.cookie);clients=[host,peer];for(const c of clients)await c.connect();
 ok(await host.roomCmd('approveSeat',{member:peerId,seat:1}));
 const all=defaultAutomationModes(),custom={...all,data:'manual',research:'manual'};
 for(const automationModes of [null,{},[],{...all,finance:'auto'},{...all,research:'bad'}]) assert.equal((await host.roomCmd('ready',{automationModes})).status,400);
 assert.equal((await host.roomCmd('ready',{member:peerId,automationModes:custom})).status,400);
 await new Promise(r=>setTimeout(r,1100));
 ok(await host.roomCmd('ready',{name:'晨星甲',brand:'晨星',country:'CN',automationModes:custom}));
 ok(await peer.roomCmd('ready',{name:'云朵乙',brand:'云朵',country:'US',automationModes:all}));
 ok(await peer.roomCmd('setCompany',{automationModes:{...all,evaluation:'manual'}}));
 assert.equal((await host.roomCmd('start')).status,400,'changing a ready preset must cancel ready');
 ok(await peer.roomCmd('ready'));
 ok(await host.roomCmd('start'));await waitFor(()=>host.s&&peer.s);ok(await host.roomCmd('pause'));
 assert.equal(host.s.automation.modules.data.mode,'manual');assert.equal(host.s.automation.modules.research.mode,'manual');
 assert.equal(peer.s.automation.modules.data.mode,'auto');assert.equal(peer.s.automation.modules.evaluation.mode,'manual');
 assert.equal(host.s.automation.cardDefault,undefined);assert.equal(host.s.postPlanSessions,undefined);
 await new Promise(r=>setTimeout(r,1100));
 const statusBefore=(await api(srv.base,`/api/r/${room}/status`)).json;
 const args={modules:['data','research'],mode:'auto',expectedRev:host.s.automation.rev,requestId:'ui:batch'};
 assert.equal((await host.cmd(1,'configureAutomationBatch',args)).json.ok,true);await waitFor(()=>host.s.automation.modules.data.mode==='auto');
 const once=(await api(srv.base,`/api/r/${room}/status`)).json;
 assert.equal((await host.cmd(1,'configureAutomationBatch',args)).json.ok,true);
 assert.equal((await api(srv.base,`/api/r/${room}/status`)).json.hash,once.hash,'transport retry must not append a command');
 const autoBefore=JSON.stringify(host.s.automation);
 assert.equal((await host.cmd(2,'configureAutomationBatch',args)).json.ok,true);
 await new Promise(r=>setTimeout(r,30));assert.equal(JSON.stringify(host.s.automation),autoBefore,'semantic retry leaves automation unchanged; world still records accepted command sequence');
 assert.equal((await peer.cmd(1,'configureAutomationBatch',{...args,companyId:host.s.charId})).json.ok,false);
 const later=(await api(srv.base,`/api/r/${room}/status`)).json;assert.equal(later.day,statusBefore.day);assert.equal(later.paused,true);assert.equal(later.hostSpeed,statusBefore.hostSpeed);
 ok(await host.roomCmd('save'));
 const dir=path.join(data,room),start=readLog(dir).find(e=>e.t==='room'&&e.name==='start');assert.deepEqual(start.args.automationSetup.map(r=>r.modes),[custom,{...all,evaluation:'manual'}]);
 const [,full]=replayHash(dir).split(' '),[,snap]=replayHash(dir,{fromStart:false}).split(' ');assert.equal(full,later.hash);assert.equal(snap,full);
 srv.proc.kill('SIGKILL');await new Promise(r=>srv.proc.once('exit',r));clients.forEach(c=>c.close());
 srv=await startServer({data,args:['--tick-ms','10000']});const restored=ok(await api(srv.base,`/api/r/${room}/status`));assert.equal(restored.hash,full);assert.equal(restored.paused,true);
 host=new Client(srv.base,room,made.cookie);clients.push(host);await host.connect();await waitFor(()=>host.s);assert.equal(host.s.automation.modules.research.mode,'auto');
});
